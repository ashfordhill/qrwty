// Writes docs/evidence/q11/contrast.md from results/checks.json (run checks.mjs first).
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { OUT } from "./lib.mjs";

const r = JSON.parse(await readFile(join(OUT, "results/checks.json"), "utf8"));
const rows = r.contrastPairs.light.map((l, i) => {
	const d = r.contrastPairs.dark[i];
	const need = l.need === 7 ? "7:1 (QR, own rule)" : `${l.need}:1`;
	const cell = (p) => `${p.ratio.toFixed(2)} ${p.pass ? "pass" : "FAIL"}`;
	return `| \`${l.fg}\` on \`${l.bg}\` | ${l.kind} | ${need} | \`${l.fgValue}\` / \`${l.bgValue}\` | ${cell(l)} | \`${d.fgValue}\` / \`${d.bgValue}\` | ${cell(d)} |`;
});
const scan = r.contrastScan;
const md = `# Q11 contrast (WCAG 2.2 AA)

Generated by \`scripts/contrast-table.mjs\` from \`results/checks.json\` (${r.generatedAt}). Ratios are
WCAG 2.x relative-luminance contrast, computed from the token values the rendered prototype
resolves in each theme. Text needs 4.5:1 (3:1 at 24 px, or 18.66 px bold). UI boundaries, focus
indicators, status markers and chart marks need 3:1 (SC 1.4.11). The QR row uses the design's own
7:1 rule. The primary button's edge is the better of its ink border and its yellow fill: in light
the ink border carries it, and in dark the fill does.

| Pair | Kind | Needs | Light values | Light | Dark values | Dark |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

## Rendered-text scan

Every visible text element in all ${r.overflow[0].states} prototype states, in light and dark at 1440 x 900, was
measured against its nearest opaque background: **${scan.checked} measurements, lowest ratio
${scan.minRatio}:1, ${scan.failures.length} failures.** Controls marked \`aria-disabled\` are exempt (SC 1.4.3)
and are still drawn distinctly (dashed edge). No text sits on a translucent surface.
`;
await writeFile(join(OUT, "contrast.md"), md);
console.log(`wrote contrast.md: ${rows.length} pairs`);
